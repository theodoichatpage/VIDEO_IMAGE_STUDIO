// Each build gets an id; open Studio tabs compare it with /build-id.json and reload themselves when idle.
import fs from 'node:fs';
const id = String(process.env.VERCEL_GIT_COMMIT_SHA || Date.now()).slice(0, 40);
fs.writeFileSync('public/build-id.json', JSON.stringify({ id }));
fs.writeFileSync('src/buildId.ts', '// Generated by scripts/write-build-id.mjs at build time.\nexport const BUILD_ID = ' + JSON.stringify(id) + ';\n');
